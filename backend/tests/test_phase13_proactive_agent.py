# ==============================================================================


def test_13_2_automatic_conditional_skip_evaluator():
    """
    Task 13.2: Verifies that conditional skip rules fire deterministically:
    - 80GG skipped if HRA present
    - 10(13A) skipped if no HRA
    - 80TTB skipped if not senior citizen
    - 80TTA skipped if senior citizen
    """
    # 1. HRA recipient
    state_hra = TaxPlanningState(
        gross_income=1000000.0,
        salary_slip_data={"basic": 50000.0, "hra": 25000.0},
        user_profile={"age": 30},
    )
    skips_hra = evaluate_auto_skips(state_hra, CANONICAL_SECTIONS_ORDER)
    assert "80GG" in skips_hra
    assert "10(13A)" not in skips_hra
    assert "80TTB" in skips_hra  # age 30 is not senior citizen

    # 2. Non-HRA recipient
    state_no_hra = TaxPlanningState(
        gross_income=1000000.0,
        salary_slip_data={"basic": 50000.0, "hra": 0.0},
        user_profile={"age": 30},
    )
    skips_no_hra = evaluate_auto_skips(state_no_hra, CANONICAL_SECTIONS_ORDER)
    assert "10(13A)" in skips_no_hra
    assert "80GG" not in skips_no_hra

    # 3. Senior Citizen
    state_senior = TaxPlanningState(
        gross_income=800000.0,
        user_profile={"age": 68},
    )
    skips_senior = evaluate_auto_skips(state_senior, CANONICAL_SECTIONS_ORDER)
    assert "80TTA" in skips_senior
    assert "80TTB" not in skips_senior


