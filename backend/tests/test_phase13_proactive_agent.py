# Task 13.9: Completion Gate Blocks Tax Computation
# ==============================================================================


def test_13_9_completion_gate_blocks_tax_computation_while_sections_pending():
    """
    Task 13.9: Asserts that a conversation CANNOT reach the tax-computation node
    while any catalog section remains in sections_pending.
    """
    state = TaxPlanningState(
        user_id=201,
        gross_income=1500000.0,
        is_salaried=True,
    )

    # Initial turn: 18 sections pending
    res = step_tax_planning_agent(state, user_message=None)
    assert len(res.elicitation.sections_pending) > 0
    assert "node_tax_computation" not in res.visited_nodes
    assert res.comparison_result is None
    assert res.final_report is None

    # Resolve first section
    res2 = step_tax_planning_agent(res, user_message="150000")
    assert len(res2.elicitation.sections_pending) > 0
    assert "node_tax_computation" not in res2.visited_nodes
    assert res2.comparison_result is None
    assert res2.final_report is None

    # Now create a state where all sections except one are resolved
    res_almost_done = res2.model_copy()
    res_almost_done.elicitation.sections_pending = ["80U"]
    res_almost_done.elicitation.current_section = "80U"

    # User is on the last section: answer it
    res_final = step_tax_planning_agent(res_almost_done, user_message="No")
    assert len(res_final.elicitation.sections_pending) == 0
    assert "node_tax_computation" in res_final.visited_nodes
    assert res_final.comparison_result is not None
    assert res_final.final_report is not None
    assert "recommended_regime" in res_final.final_report


