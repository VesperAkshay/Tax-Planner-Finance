# Task 13.4: Natural Language Response Parsing
# ==============================================================================


def test_13_4_natural_language_response_parsing():
    """
    Task 13.4: Verifies response parsing maps amounts to declared and negations to not_applicable.
    """
    # Numeric amounts
    status, amt, _ = parse_elicitation_response("I put 150000 in PPF", "80C")
    assert status == "declared"
    assert amt == 150000.0

    status, amt, _ = parse_elicitation_response("₹50,000 in NPS", "80CCD(1B)")
    assert status == "declared"
    assert amt == 50000.0

    status, amt, _ = parse_elicitation_response("25k health insurance", "80D")
    assert status == "declared"
    assert amt == 25000.0

    # Negative / None responses
    for neg in ["No", "None", "N/A", "no deductions", "I don't have this", "zero", "nil"]:
        status, amt, _ = parse_elicitation_response(neg, "80G")
        assert status == "not_applicable"
        assert amt == 0.0
