# Task 13.7 & 13.12: Cross-Session Kill and Resumption
# ==============================================================================


def test_13_7_cross_session_kill_and_resumption(memory_session: Session):
    """
    Task 13.7 / 13.12: Simulates killing the session mid-conversation, restarting it,
    and verifying it resumes from the exact next pending section.
    """
    user_id = 401
    fy = "2025-2026"

    # Step 1: User declares 80C in first session
    record_elicited_deduction(
        session=memory_session,
        user_id=user_id,
        section="80C",
        amount=150000.0,
        status="declared",
        financial_year=fy,
    )

    # Step 2: 80CCD(1B) is answered as not_applicable
    record_elicited_deduction(
        session=memory_session,
        user_id=user_id,
        section="80CCD(1B)",
        amount=0.0,
        status="not_applicable",
        financial_year=fy,
    )

    # Step 3: 80GG is automatically skipped
    save_elicitation_step(
        session=memory_session,
        user_id=user_id,
        section_code="80GG",
        state=ElicitationStateEnum.skipped,
        financial_year=fy,
        skip_reason="Salary slip contains HRA component",
    )

    # --- SESSION KILL: Memory is cleared, new process starts ---

    # Step 4: Resume session by loading state from DB
    resumed_elicitation = load_elicitation_state(
        session=memory_session,
        user_id=user_id,
        financial_year=fy,
    )

    # Verify loaded progress
    assert "80C" in resumed_elicitation.sections_answered
    assert resumed_elicitation.sections_answered["80C"]["amount"] == 150000.0
    assert "80CCD(1B)" in resumed_elicitation.sections_answered
    assert resumed_elicitation.sections_answered["80CCD(1B)"]["status"] == "not_applicable"
    assert "80GG" in resumed_elicitation.sections_skipped
    assert "80C" not in resumed_elicitation.sections_pending
    assert "80CCD(1B)" not in resumed_elicitation.sections_pending
    assert "80GG" not in resumed_elicitation.sections_pending

    # Next pending section must be 80CCD(2) (the 3rd canonical section)
    assert resumed_elicitation.current_section == "80CCD(2)"

    # Step 5: Execute turn using resumed state
    resumed_state = TaxPlanningState(
        user_id=user_id,
        gross_income=1400000.0,
        elicitation=resumed_elicitation,
    )
    turn_res = step_tax_planning_agent(resumed_state, user_message=None)
    assert "80CCD(2)" in turn_res.current_agent_message


