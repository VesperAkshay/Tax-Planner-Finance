# Task 13.8: Agent First Message Is Proactive
# ==============================================================================


def test_13_8_agent_first_message_is_proactive_across_profiles():
    """
    Task 13.8: Runs the flow across 3 synthetic profiles; asserts the agent's first
    message on each pending section is generated by the agent, not preceded by any
    user prompt about that topic.
    """
    # Profile A: Standard Salaried Employee
    state_a = TaxPlanningState(
        user_id=101,
        gross_income=1200000.0,
        is_salaried=True,
        salary_slip_data={"basic": 60000.0, "hra": 30000.0, "gross_pay": 100000.0, "employee_pf": 7200.0},
    )

    # Step 1: Agent starts conversation proactively without any user message
    res_1 = step_tax_planning_agent(state_a, user_message=None)
    assert res_1.current_agent_message is not None
    # Must proactively ask about Section 80C (first canonical pending section)
    assert "80C" in res_1.current_agent_message
    assert res_1.elicitation.current_section == "80C"

    # User responds to 80C
    res_2 = step_tax_planning_agent(res_1, user_message="I invest 150000 in PPF and ELSS")
    assert "80C" in res_2.elicitation.sections_answered
    assert res_2.elicitation.sections_answered["80C"]["status"] == "declared"

    # Next message MUST proactively ask about the next pending section (80CCD(1B)), NOT user prompted
    assert res_2.current_agent_message is not None
    assert "80CCD(1B)" in res_2.current_agent_message
    assert res_2.elicitation.current_section == "80CCD(1B)"

    # Profile B: Senior Citizen Consultant (Age >= 60, no salary slip)
    state_b = TaxPlanningState(
        user_id=102,
        gross_income=900000.0,
        is_salaried=False,
        user_profile={"age": 65, "is_senior_citizen": True},
    )
    res_b1 = step_tax_planning_agent(state_b, user_message=None)
    assert res_b1.current_agent_message is not None
    assert "80C" in res_b1.current_agent_message
    # 80TTA should be automatically skipped for senior citizen (80TTB applies instead)
    assert "80TTA" in res_b1.elicitation.sections_skipped

    # Profile C: Salaried Individual without HRA
    state_c = TaxPlanningState(
        user_id=103,
        gross_income=800000.0,
        is_salaried=True,
        salary_slip_data={"basic": 50000.0, "hra": 0.0, "gross_pay": 66667.0},
    )
    res_c1 = step_tax_planning_agent(state_c, user_message=None)
    # HRA 10(13A) should be skipped because salary slip has 0 HRA
    assert "10(13A)" in res_c1.elicitation.sections_skipped
    # 80GG should NOT be skipped because HRA is 0
    assert "80GG" not in res_c1.elicitation.sections_skipped


