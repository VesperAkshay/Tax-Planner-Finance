# Task 13.10: Intercept Short-Circuit Attempts
# ==============================================================================


def test_13_10_short_circuit_redirects_to_pending_section():
    """
    Task 13.10: Simulates user trying to skip ahead ("just calculate my tax") before all
    sections are resolved; asserts the agent redirects back to the next pending section.
    """
    state = TaxPlanningState(
        user_id=301,
        gross_income=1200000.0,
        is_salaried=True,
    )
    res_init = step_tax_planning_agent(state, user_message=None)
    assert res_init.elicitation.current_section == "80C"

    # User attempts to short-circuit
    short_circuit_prompts = [
        "just calculate my tax",
        "calculate my tax now please",
        "skip ahead and give me the recommendation",
        "what is my tax liability?",
        "tell me how much tax I owe",
    ]

    for phrase in short_circuit_prompts:
        step_res = step_tax_planning_agent(res_init, user_message=phrase)
        # 1. Tax computation node MUST NOT be visited
        assert "node_tax_computation" not in step_res.visited_nodes
        assert step_res.comparison_result is None
        assert step_res.final_report is None

        # 2. Redirect message must be present and explain why
        assert step_res.redirect_message is not None
        assert "Before we calculate your final tax liability" in step_res.redirect_message
        # 3. Must remind the user about the currently pending section
        assert "Section 80C" in step_res.redirect_message
        assert step_res.elicitation.current_section == "80C"


