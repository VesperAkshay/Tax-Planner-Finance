def build_dataset() -> List[Dict[str, str]]:
    """Builds and deduplicates the labeled dataset."""
    dataset: List[Dict[str, str]] = []
    seen = set()
    sample_id = 1

    for category, narrations in DATASET_PATTERNS.items():
        for narration in narrations:
            clean_text = narration.strip()
            if not clean_text or clean_text.lower() in seen:
                continue
            seen.add(clean_text.lower())
            dataset.append({
                "id": str(sample_id),
                "description": clean_text,
                "category": category,
            })
            sample_id += 1

    return dataset


def save_dataset_csv(dataset: List[Dict[str, str]], output_path: Path):
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["id", "description", "category"])
        writer.writeheader()
        writer.writerows(dataset)


def generate_readme(dataset: List[Dict[str, str]], output_path: Path):
    category_counts: Dict[str, int] = {}
    for row in dataset:
        c = row["category"]
        category_counts[c] = category_counts.get(c, 0) + 1

    lines = [
        "# Labeled Transaction Dataset for ML Categorization (Task 3.1)\n",
        f"**Total Samples**: {len(dataset)}\n",
        "**Target Domain**: Indian Retail Banking (UPI, NEFT, RTGS, IMPS, ACH, POS, ATM, NetBanking)\n",
        "## Category Distribution\n",
        "| Category | Sample Count | Sample Narrations |",
        "|---|---|---|",
    ]

    for cat, count in sorted(category_counts.items()):
        samples = [r["description"] for r in dataset if r["category"] == cat][:2]
        sample_str = "<br>".join(f"`{s}`" for s in samples)
        lines.append(f"| {cat} | {count} | {sample_str} |")

    lines.append("\n## Reproduction\n")
    lines.append("Regenerate the dataset at any time:\n")
    lines.append("```bash\nuv run python data/categorization/generate_labeled_dataset.py\n```\n")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    dataset = build_dataset()
    save_dataset_csv(dataset, OUTPUT_FILE)
    generate_readme(dataset, OUTPUT_DIR / "README.md")
    print(f"Successfully generated {len(dataset)} labeled transaction samples into:")
    print(f"  {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
